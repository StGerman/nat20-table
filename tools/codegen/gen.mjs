// `npm run gen`: contract crate -> JSON Schema bundle -> schema hash -> TS types.
// Everything it writes is generated: never edit those files by hand (CLAUDE.md Rule 1).
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const out = (p) => path.join(root, p);

const schemaText = execFileSync("cargo", ["run", "--quiet", "--locked", "-p", "nat20-api-contract", "--bin", "export-schema"], {
  cwd: root,
  encoding: "utf8",
  stdio: ["ignore", "pipe", "inherit"],
});
fs.writeFileSync(out("generated/nat20-api.schema.json"), schemaText);
const sha = createHash("sha256").update(schemaText).digest("hex");
fs.writeFileSync(out("generated/nat20-api.schema.sha256"), sha + "\n");

const schema = JSON.parse(schemaText);
const banner = [
  "// GENERATED by `npm run gen` from crates/nat20-api-contract. Do not edit (CLAUDE.md Rule 1).",
  `// Schema sha256: ${sha}`,
].join("\n");
// Root is Nat20Api; every $def is emitted as a named export.
let ts = await compile(schema, "Nat20Api", { bannerComment: banner, unreachableDefinitions: true, additionalProperties: false });
ts += `\n/** SHA-256 of the schema these types were generated from. Compare with \`hello.schema_sha256\`. */\nexport const SCHEMA_SHA256 = "${sha}";\n`;
fs.writeFileSync(out("packages/engine-client/src/generated/api.ts"), ts);
console.log(`generated: schema ${sha.slice(0, 12)}, ${Object.keys(schema.$defs ?? {}).length} types`);
