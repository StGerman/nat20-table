// `npm run gen`: contract crate -> JSON Schema bundles (wire, scene file) -> schema hash -> TS types.
// Everything it writes is generated: never edit those files by hand (CLAUDE.md Rule 1).
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const out = (p) => path.join(root, p);

const exportSchema = (which) =>
  execFileSync("cargo", ["run", "--quiet", "--locked", "-p", "nat20-api-contract", "--bin", "export-schema", which], {
    cwd: root,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "inherit"],
  });
// Two schemas: the wire (root Nat20Api) and the scene file (root SceneFile). One hash covers both,
// in that order, so `hello.schema_sha256` changes when either does.
const schemaText = exportSchema("api");
const sceneText = exportSchema("scene");
fs.writeFileSync(out("generated/nat20-api.schema.json"), schemaText);
fs.writeFileSync(out("generated/nat20-scene.schema.json"), sceneText);
const sha = createHash("sha256").update(schemaText).update(sceneText).digest("hex");
fs.writeFileSync(out("generated/nat20-api.schema.sha256"), sha + "\n");

const banner = [
  "// GENERATED by `npm run gen` from crates/nat20-api-contract. Do not edit (CLAUDE.md Rule 1).",
  `// Schema sha256: ${sha}`,
].join("\n");
const compileOptions = { bannerComment: banner, unreachableDefinitions: true, additionalProperties: false };

const schema = JSON.parse(schemaText);
// Root is Nat20Api; every $def is emitted as a named export.
let ts = await compile(forTypeScript(schema), "Nat20Api", compileOptions);
ts += `\n/** SHA-256 of the schemas these types were generated from. Compare with \`hello.schema_sha256\`. */\nexport const SCHEMA_SHA256 = "${sha}";\n`;
fs.writeFileSync(out("packages/engine-client/src/generated/api.ts"), ts);

const scene = JSON.parse(sceneText);
// Root is SceneFile. Shared vocabulary (Handle, Side, ...) is emitted again here; the client
// re-exports this module as the `scene` namespace so the names don't clash.
const sceneTs = await compile(forTypeScript(scene), "SceneFile", compileOptions);
fs.writeFileSync(out("packages/engine-client/src/generated/scene.ts"), sceneTs);
console.log(`generated: schema ${sha.slice(0, 12)}, ${Object.keys(schema.$defs ?? {}).length} wire types, ${Object.keys(scene.$defs ?? {}).length + 1} scene types`);

// A copy of the schema reshaped where json-schema-to-typescript mishandles valid JSON Schema.
// The committed schema and its hash are untouched; only the TS input changes.
function forTypeScript(schema) {
  const copy = structuredClone(schema);
  // 1. `{ $ref, description }`: the generator emits a duplicate type (`PointFt1`) per such field.
  //    `{ description, allOf: [{ $ref }] }` keeps the field's doc and references the one type.
  const wrapRefs = (node) => {
    if (Array.isArray(node)) return node.forEach(wrapRefs);
    if (!node || typeof node !== "object") return;
    if (typeof node.$ref === "string" && Object.keys(node).length > 1) {
      node.allOf = [{ $ref: node.$ref }];
      delete node.$ref;
    }
    Object.values(node).forEach(wrapRefs);
  };
  wrapRefs(copy);
  // 2. A struct with a `#[serde(flatten)]` tagged enum becomes `properties` plus `oneOf`, which the
  //    generator names `Request1`. Split the union out under the Rust enum's name.
  const flattened = { Request: "Command", Event: "EventKind" };
  for (const [name, def] of Object.entries(copy.$defs ?? {})) {
    if (!def.oneOf || !def.properties) continue;
    const unionName = flattened[name];
    if (!unionName) throw new Error(`${name} flattens a tagged enum; add its Rust enum name to \`flattened\` in tools/codegen/gen.mjs`);
    if (copy.$defs[unionName]) throw new Error(`${unionName} already exists in the schema`);
    copy.$defs[unionName] = { oneOf: def.oneOf };
    const { oneOf, description, ...struct } = def;
    copy.$defs[name] = { description, allOf: [struct, { $ref: `#/$defs/${unionName}` }] };
  }
  return copy;
}
